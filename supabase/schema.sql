create extension if not exists pgcrypto;

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null default 'Beverage',
  price numeric not null default 0,
  badge text default 'Featured',
  description text default 'Freshly prepared drink.',
  accent text default 'from-amber-200 via-orange-100 to-white',
  emoji text default '☕',
  image_url text,
  type text not null default 'drink',
  is_active boolean not null default true,
  sizes jsonb not null default '[{"label":"Classic","volume":"500ML","price":0},{"label":"Large","volume":"1000ML","price":4}]'::jsonb,
  toppings jsonb not null default '[]'::jsonb
);

alter table public.products
  add column if not exists is_active boolean not null default true,
  add column if not exists image_url text;

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  customer_name text,
  customer_phone text,
  customer_email text,
  total numeric not null default 0,
  status text not null default 'pending',
  payment_status text not null default 'pending',
  midtrans_order_id text,
  midtrans_transaction_id text,
  payment_type text,
  payment_method text not null default 'midtrans',
  qris_proof_path text
);

alter table public.orders
  add column if not exists customer_phone text;

alter table public.orders
  add column if not exists customer_email text;

alter table public.orders
  add column if not exists payment_status text not null default 'pending',
  add column if not exists midtrans_order_id text,
  add column if not exists midtrans_transaction_id text,
  add column if not exists payment_type text,
  add column if not exists payment_method text not null default 'midtrans',
  add column if not exists qris_proof_path text;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'qris-payment-proofs',
  'qris-payment-proofs',
  false,
  5242880,
  array['image/jpeg', 'image/png', 'image/webp']
)
on conflict (id) do update
set public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

create unique index if not exists orders_midtrans_order_id_key
  on public.orders (midtrans_order_id)
  where midtrans_order_id is not null;

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid references public.orders(id) on delete cascade,
  product_id bigint references public.products(id),
  product_name text not null,
  size text not null default 'Classic',
  quantity integer not null default 1,
  toppings jsonb not null default '[]'::jsonb,
  unit_price numeric not null default 0
);

alter table public.order_items
  add column if not exists size text not null default 'Classic';

create table if not exists public.reviews (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  review_text text not null check (char_length(btrim(review_text)) between 10 and 1000),
  display_name text,
  is_anonymous boolean not null default true,
  is_approved boolean not null default false,
  constraint reviews_identity_consistency check (
    (is_anonymous and display_name is null)
    or (not is_anonymous and display_name is not null and char_length(btrim(display_name)) between 1 and 80)
  )
);

alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.reviews enable row level security;

drop policy if exists "Allow public read products" on public.products;
create policy "Allow public read products"
on public.products
for select
to public
using (true);

drop policy if exists "Allow public insert orders" on public.orders;
create policy "Allow public insert orders"
on public.orders
for insert
to public
with check (true);

drop policy if exists "Allow public insert order items" on public.order_items;
create policy "Allow public insert order items"
on public.order_items
for insert
to public
with check (true);

drop policy if exists "Allow public select orders" on public.orders;
create policy "Allow public select orders"
on public.orders
for select
to public
using (true);

drop policy if exists "Allow public select order items" on public.order_items;
create policy "Allow public select order items"
on public.order_items
for select
to public
using (true);

grant select on public.reviews to anon, authenticated;

drop policy if exists "Allow public read approved reviews" on public.reviews;
create policy "Allow public read approved reviews"
on public.reviews
for select
to anon, authenticated
using (is_approved = true);

